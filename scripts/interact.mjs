import { createRequire } from 'node:module';
const require = createRequire('/usr/lib/node_modules/'); const { chromium } = require('playwright');
import { serve } from './serve.mjs';
const srv = await serve(4177); const b = await chromium.launch(); const R = []; const ok = (n, c, x = '') => { R.push(`${c ? 'PASS' : 'FAIL'}  ${n} ${x}`); };
const errs = [];
// ---- desktop
let p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('console', m => m.type() === 'error' && !/404/.test(m.text()) && errs.push(m.text())); p.on('pageerror', e => errs.push(String(e)));
await p.goto('http://localhost:4177/', { waitUntil: 'networkidle' });
await p.evaluate(() => document.documentElement.style.scrollBehavior = 'auto');
ok('nav sticky', await p.evaluate(() => getComputedStyle(document.querySelector('.nav')).position) === 'sticky');
await p.evaluate(() => scrollTo(0, 400)); await p.waitForTimeout(150);
ok('nav shadow after scroll', await p.evaluate(() => document.querySelector('.nav').classList.contains('is-scrolled')));
await p.click('.nav-link[href="/#faq"]'); await p.waitForTimeout(400);
ok('anchor scroll to FAQ', await p.evaluate(() => Math.abs(document.querySelector('#faq').getBoundingClientRect().top) < 300));
ok('scroll-spy highlights FAQ', await p.evaluate(() => document.querySelector('.nav-link[href="/#faq"]').classList.contains('is-active')));
const faq = await p.$$('.faq-q');
ok('FAQ first open by default', await faq[0].getAttribute('aria-expanded') === 'true');
await faq[2].click(); await p.waitForTimeout(350);
ok('FAQ one-open-at-a-time', (await p.$$eval('.faq-item.is-open', e => e.length)) === 1 && await faq[2].getAttribute('aria-expanded') === 'true' && await faq[0].getAttribute('aria-expanded') === 'false');
await faq[2].focus(); await p.keyboard.press('Enter'); await p.waitForTimeout(350);
ok('FAQ keyboard toggle closes', await faq[2].getAttribute('aria-expanded') === 'false');
await p.evaluate(() => scrollTo(0, 0)); await p.waitForTimeout(2600);
ok('funnel auto-played to After', await p.evaluate(() => document.querySelector('[data-funnel]').dataset.view) === 'after');
await p.click('.toggle [data-set="before"]'); await p.waitForTimeout(500);
ok('funnel toggle -> Before 31%', (await p.textContent('.result strong')).trim() === '31%');
ok('KYC chip visible', await p.evaluate(() => document.querySelector('[data-kyc]').classList.contains('is-in')));
const first = await p.evaluate(() => document.querySelector('.ind-carousel').scrollLeft);
await p.click('.arrow-next'); await p.waitForTimeout(900);
ok('carousel next scrolls', await p.evaluate(() => document.querySelector('.ind-carousel').scrollLeft) > first + 100);
ok('prev enabled after scroll', await p.evaluate(() => !document.querySelector('.arrow-prev').disabled));
ok('hero primary CTA opens intake form', (await p.getAttribute('.hero-ctas .btn-primary', 'href')) === '/start/');
ok('WhatsApp link', (await p.$$eval('a[href^="https://wa.me/923372186894"]', a => a.length)) >= 2);
ok('external links noopener', await p.$$eval('a[target="_blank"]', a => a.every(x => /noopener/.test(x.rel))));
ok('single h1', (await p.$$eval('h1', e => e.length)) === 1);
// ---- work filters
await p.goto('http://localhost:4177/work/', { waitUntil: 'networkidle' });
ok('work: 5 cards visible', (await p.$$eval('.work-grid>li:not([hidden])', e => e.length)) === 5);
await p.click('.tab[data-filter="gov-tech"]'); await p.waitForTimeout(500);
ok('work: gov-tech filter 2 cards + URL', (await p.$$eval('.work-grid>li:not([hidden])', e => e.length)) === 2 && p.url().endsWith('/work/gov-tech/'));
await p.focus('.tab[aria-selected="true"]'); await p.keyboard.press('ArrowRight'); await p.waitForTimeout(500);
ok('work: arrow key moves to Ed-tech', p.url().endsWith('/work/ed-tech/'));
await p.goBack(); await p.waitForTimeout(500);
ok('work: back restores gov-tech', (await p.$$eval('.work-grid>li:not([hidden])', e => e.length)) === 2);
await p.goto('http://localhost:4177/work/ed-tech/', { waitUntil: 'networkidle' });
ok('work/ed-tech deep link shows 2', (await p.$$eval('.work-grid>li:not([hidden])', e => e.length)) === 2);
await p.click('.work-grid>li:not([hidden]) .case-card'); await p.waitForLoadState('networkidle');
ok('card -> case page', /\/work\/(apply-one|str)/.test(p.url()));
const nxt = await p.getAttribute('.next-card', 'href'); await p.click('.next-card'); await p.waitForLoadState('networkidle');
ok('next project link works', p.url().endsWith(nxt));
const r404 = await p.goto('http://localhost:4177/nope', { waitUntil: 'networkidle' });
ok('404 page status+content', r404.status() === 404 && (await p.textContent('h1')).includes('wrong'));
// ---- mobile menu
const m = await b.newPage({ viewport: { width: 390, height: 844 } });
m.on('console', x => x.type() === 'error' && errs.push(x.text()));
await m.goto('http://localhost:4177/', { waitUntil: 'networkidle' });
ok('mobile: burger visible, desktop links hidden', await m.isVisible('.nav-burger') && !(await m.isVisible('.nav-links')));
await m.click('.nav-burger'); await m.waitForTimeout(100);
ok('mobile: menu opens fullscreen', await m.isVisible('#mobile-menu') && (await m.evaluate(() => document.querySelector('#mobile-menu').getBoundingClientRect().height)) >= 844);
await m.keyboard.press('Escape'); await m.waitForTimeout(100);
ok('mobile: Esc closes menu', !(await m.isVisible('#mobile-menu')));
await m.click('.nav-burger'); await m.click('.mm-item:nth-of-type(1)'); await m.waitForTimeout(1500);
ok('mobile: link closes menu + scrolls to services', !(await m.isVisible('#mobile-menu')) && (await m.evaluate(() => document.querySelector('#services').getBoundingClientRect().top)) < 200);
// min tap target
const small = await m.$$eval('.btn, .faq-q, .nav-burger, .mm-item', e => e.filter(x => x.offsetParent && x.getBoundingClientRect().height < 44).map(x => x.className + Math.round(x.getBoundingClientRect().height)));
ok('mobile: buttons/FAQ rows/menu >= 44px tall', small.length === 0, JSON.stringify(small));
ok('no console errors', errs.length === 0, errs.slice(0, 3).join(' | '));
console.log(R.join('\n')); await b.close(); srv.close();
